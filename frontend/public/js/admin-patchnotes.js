const PATCH_SCALE_COLOR = {
  '대격변': '#c62828|#ffebee',
  '중간급': '#1565c0|#e3f2fd',
  '소규모': '#2e7d32|#e8f5e9',
};

function formatPatchDate(d) {
  return `${d.slice(0, 4)}.${d.slice(4, 6)}.${d.slice(6, 8)}`;
}

function renderPatchNotes() {
  const el = document.getElementById('patch-notes-list');
  if (!el) return;
  el.innerHTML = PATCH_NOTES.map((n, i) => {
    const [fg, bg] = (PATCH_SCALE_COLOR[n.scale] || '#555|#eee').split('|');
    return `<button type="button" class="patch-row" onclick="openPatchNote(${i})">
      <span class="patch-version">${n.version}</span>
      <span class="patch-date">${n.date}</span>
      <span class="patch-title">${escapeHtml(n.title)}</span>
      <span class="patch-scale" style="color:${fg};background:${bg}">${n.scale}</span>
    </button>`;
  }).join('');
}

function openPatchNote(i) {
  const n = PATCH_NOTES[i];
  if (!n) return;
  const [fg, bg] = (PATCH_SCALE_COLOR[n.scale] || '#555|#eee').split('|');
  const block = (title, items, cls) => items && items.length
    ? `<div class="patch-section-title">${title}</div><ul class="${cls}">${items.map(c => `<li>${c}</li>`).join('')}</ul>`
    : '';

  document.getElementById('patch-modal-title').innerHTML =
    `<span><span class="patch-version">${n.version}</span> ${escapeHtml(n.title)}
     <span class="patch-scale" style="color:${fg};background:${bg};margin-left:8px">${n.scale}</span></span>`;

  document.getElementById('patch-modal-body').innerHTML = `
    <div class="patch-meta">${formatPatchDate(n.date)} 업데이트</div>
    <div class="patch-summary">${n.summary}</div>

    ${block('⚙️ 시스템은 이렇게 바뀌었습니다', n.system, 'patch-list')}
    ${block('🖥 화면은 이렇게 바뀌었습니다', n.screen, 'patch-list')}

    ${n.howto.length ? `
      <div class="patch-section-title">👉 직접 눌러보세요</div>
      <ol class="patch-howto">${n.howto.map(h => `
        <li><b>${h.step}</b><div>${h.detail}</div></li>`).join('')}</ol>` : ''}

    <div class="patch-author">
      작업자 <b>${escapeHtml(n.author)}</b>
    </div>
  `;
  document.getElementById('patch-modal').classList.add('open');
}

document.addEventListener('DOMContentLoaded', renderPatchNotes);
